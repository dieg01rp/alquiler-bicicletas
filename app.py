@st.cache_resource
def load_model_and_meta(ckpt_path: str = "artefactos/rnn_bike_model.pt"):
    if not os.path.exists(ckpt_path):
        return None
    ckpt = torch.load(ckpt_path, map_location="cpu", weights_only=False)
    arch = ckpt["arquitectura"]
    model = RNNRegressor(
        n_features=arch["n_features"],
        hidden=arch["hidden"],
        layers=arch["layers"],
    )
    model.load_state_dict(ckpt["state_dict"])
    model.eval()
    return ckpt, model


@st.cache_data
def load_series_and_csvs(csv_path: str = "hour.csv", ckpt_path: str = "artefactos/rnn_bike_model.pt"):
    if not os.path.exists(csv_path) or not os.path.exists(ckpt_path):
        return None

    ckpt = torch.load(ckpt_path, map_location="cpu", weights_only=False)
    features = ckpt["features"]
    scale_cols = ckpt["scale_cols"]
    mean = np.array(ckpt["scaler_mean"], dtype=np.float64)
    scale = np.array(ckpt["scaler_scale"], dtype=np.float64)

    raw = pd.read_csv(csv_path)
    raw["dteday"] = pd.to_datetime(raw["dteday"])
    raw["ts"] = raw["dteday"] + pd.to_timedelta(raw["hr"], unit="h")
    raw = raw.sort_values("ts").reset_index(drop=True)

    full_range = pd.date_range(raw["ts"].min(), raw["ts"].max(), freq="1h")
    df = raw.set_index("ts").reindex(full_range)
    df.index.name = "ts"
    df["falta_registro"] = df["cnt"].isna().astype(int)
    df["cnt"] = df["cnt"].fillna(0.0)
    for c in ["temp", "hum", "windspeed"]:
        df[c] = df[c].ffill()

    holiday_dia = raw.groupby("dteday")["holiday"].first()
    df["date"] = df.index.normalize()
    df["hr"] = df.index.hour
    df["weekday"] = df.index.dayofweek
    df["holiday"] = df["date"].map(holiday_dia).fillna(0).astype(int)
    df["workingday"] = ((df["weekday"] < 5) & (df["holiday"] == 0)).astype(int)

    cal = pd.DataFrame(index=df.index)
    cal["hr_sin"] = np.sin(2 * np.pi * df["hr"] / 24)
    cal["hr_cos"] = np.cos(2 * np.pi * df["hr"] / 24)
    cal["wd_sin"] = np.sin(2 * np.pi * df["weekday"] / 7)
    cal["wd_cos"] = np.cos(2 * np.pi * df["weekday"] / 7)
    cal["workingday"] = df["workingday"]
    cal["holiday"] = df["holiday"]
    cal_next = cal.shift(-1).add_suffix("_t1")

    S = pd.concat([df[["cnt", "temp", "hum", "windspeed"]], cal_next], axis=1)
    S["y"] = df["cnt"].shift(-1)
    S = S.iloc[:-1].copy()

    # Escalamiento con los parámetros exactos ajustados en train
    F = S[features].copy()
    F[scale_cols] = (F[scale_cols].values - mean) / scale
    F_arr = F.values.astype(np.float32)

    n = len(S)
    n_tr = int(n * 0.70)
    n_va = int(n * 0.15)
    splits = {
        "train": (0, n_tr),
        "val": (n_tr, n_tr + n_va),
        "test": (n_tr + n_va, n),
    }

    # Cargar tablas de resultados si existen
    df_val = pd.read_csv("artefactos/resultados_validacion.csv") if os.path.exists("artefactos/resultados_validacion.csv") else None
    df_test = pd.read_csv("artefactos/resultados_test.csv", index_col=0) if os.path.exists("artefactos/resultados_test.csv") else None
    df_preds = pd.read_csv("artefactos/predicciones_test.csv", index_col=0, parse_dates=True) if os.path.exists("artefactos/predicciones_test.csv") else None

    return {
        "df": df,
        "S": S,
        "F_arr": F_arr,
        "mean": mean,
        "scale": scale,
        "splits": splits,
        "df_val": df_val,
        "df_test": df_test,
        "df_preds": df_preds,
    }


def predict_single(model: nn.Module, x_win: np.ndarray, y_mean: float, y_std: float) -> float:
    with torch.no_grad():
        xt = torch.from_numpy(x_win[None, :, :])  # (1, L, F)
        y_sc = float(model(xt).item())
    return max(y_sc * y_std + y_mean, 0.0)


def check_weather_alert(df: pd.DataFrame, ts: pd.Timestamp):
    w_now = df.loc[ts, ["temp", "hum", "windspeed"]]
    w_prev = df.loc[ts - pd.Timedelta(hours=3), ["temp", "hum", "windspeed"]]
    d = (w_now - w_prev).abs()
    reasons = []
    if d["temp"] > 0.08:
        reasons.append(f"Δ temp = {d['temp']*41:.1f} °C ({d['temp']:.3f} norm.)")
    if d["hum"] > 0.15:
        reasons.append(f"Δ humedad = {d['hum']*100:.0f} % ({d['hum']:.3f} norm.)")
    if d["windspeed"] > 0.15:
        reasons.append(f"Δ viento = {d['windspeed']*67:.1f} km/h ({d['windspeed']:.3f} norm.)")
    return len(reasons) > 0, reasons, w_now, d


